package aibouncer

import (
	"fmt"
	"sort"
	"strings"
)

// Action is what the middleware does with a request.
type Action int

const (
	// Allow passes the request to the next handler.
	Allow Action = iota
	// Block answers with 403 Forbidden.
	Block
)

func (a Action) String() string {
	if a == Block {
		return "block"
	}
	return "allow"
}

// MarshalText implements encoding.TextMarshaler.
func (a Action) MarshalText() ([]byte, error) { return []byte(a.String()), nil }

// Policy decides what happens to AI agents. The zero value allows every genuine agent and blocks
// requests that impersonate one.
//
// Rules are applied in order: impostors are blocked unless AllowSpoofed is set; then a rule for
// the agent's ID wins; then the rule for its purpose; otherwise the request is allowed.
// Requests that do not claim to be an AI agent are always allowed: aibouncer is not a general
// bot-management product.
type Policy struct {
	// Purposes sets the action per purpose, e.g. {PurposeTraining: Block}.
	Purposes map[Purpose]Action
	// Agents sets the action per agent ID and overrides Purposes, e.g. {"openai-oai-searchbot": Allow}.
	Agents map[string]Action
	// AllowSpoofed lets requests that fail verification through to the purpose and agent rules
	// instead of blocking them outright.
	AllowSpoofed bool
}

// Decide returns the action for a verified (or unverifiable, or spoofed) agent claim.
func (p Policy) Decide(agent *Agent, verdict Verdict) Action {
	if agent == nil || verdict == NotAI {
		return Allow
	}
	if verdict == Spoofed && !p.AllowSpoofed {
		return Block
	}
	return p.actionFor(agent)
}

func (p Policy) actionFor(agent *Agent) Action {
	if action, ok := p.Agents[agent.ID]; ok {
		return action
	}
	if action, ok := p.Purposes[agent.Purpose]; ok {
		return action
	}
	return Allow
}

// RobotsTxt renders the policy as a robots.txt section that disallows every blocked agent with
// a robots.txt token, including control tokens such as Google-Extended and Applebot-Extended
// that can only be expressed in robots.txt. Append it to your existing robots.txt.
//
// robots.txt is advisory. Several operators document that user-initiated fetchers may ignore
// it, which is why the middleware enforces the same policy on the request path.
func (p Policy) RobotsTxt(c *Catalog) string {
	var tokens []string
	seen := map[string]bool{}
	for i := range c.Agents {
		agent := &c.Agents[i]
		if agent.RobotsToken == "" || p.actionFor(agent) != Block || seen[strings.ToLower(agent.RobotsToken)] {
			continue
		}
		seen[strings.ToLower(agent.RobotsToken)] = true
		tokens = append(tokens, agent.RobotsToken)
	}
	sort.Strings(tokens)

	var b strings.Builder
	fmt.Fprintf(&b, "# AI crawler policy generated by aibouncer %s (https://github.com/emorilebo/aibouncer)\n", Version)
	if len(tokens) == 0 {
		b.WriteString("# No AI agents are blocked by this policy.\n")
		return b.String()
	}
	for _, token := range tokens {
		fmt.Fprintf(&b, "User-agent: %s\n", token)
	}
	b.WriteString("Disallow: /\n")
	return b.String()
}
